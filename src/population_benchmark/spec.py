def enumeration_digest(plan: Plan) -> str:
    """Compact exact digest of every frozen source/band assignment."""
    test = [
        [episode.episode_id, episode.history_index, episode.cell_index,
         episode.episode_index, episode.base_index, episode.n_sources]
        for episode in plan.test_episodes()
    ]
    calibration = [
        [episode.episode_id, episode.history_index, episode.cell_index,
         episode.episode_index, episode.base_index, episode.n_sources]
        for episode in plan.calibration_episode_list()
    ]
    return sha256_json({"test": test, "calibration": calibration})


def summary(plan: Plan) -> dict[str, Any]:
    """Review-sized plan summary (counts, bands, digest)."""
    test = plan.test_episodes()
    calibration = plan.calibration_episode_list()
    per_history_test: dict[str, int] = {name: 0 for name in plan.history_ids}
    per_history_cal: dict[str, int] = {name: 0 for name in plan.history_ids}
    for episode in test:
        per_history_test[episode.history_id] += 1
    for episode in calibration:
        per_history_cal[episode.history_id] += 1
    bandwidth_base = REFERENCE_INDEX_BASE + plan.reference_files
    return {
        "label": plan.label,
        "history_ids": list(plan.history_ids),
        "history_seeds": list(plan.history_seeds),
        "cells": [[family, severity] for family, severity in plan.cells],
        "cell_count": plan.cell_count,
        "episodes_per_cell": plan.episodes_per_cell,
        "test_episode_count": len(test),
        "calibration_episode_count": len(calibration),
        "test_episodes_per_history": per_history_test,
        "calibration_episodes_per_history": per_history_cal,
        "windows_per_horizon": {horizon: len(test) for horizon in plan.horizons},
        "window_sizes": {horizon: plan.window_size(horizon) for horizon in plan.horizons},
        "requested_fault_counts": {
            horizon: list(plan.fault_counts(horizon)) for horizon in plan.horizons
        },
        "block_fault_counts": list(block_fault_counts(plan.block_files)),
        "source_bands": {
            "reference": [REFERENCE_INDEX_BASE, REFERENCE_INDEX_BASE + plan.reference_files],
            "bandwidth": [bandwidth_base, bandwidth_base + plan.bandwidth_files],
            "calibration": [plan.calibration_index_base, plan.calibration_index_base + len(calibration) * plan._episode_sources],
            "test": [plan.test_index_base, plan.test_index_base + len(test) * plan._episode_sources],
        },
        "enumeration_sha256": enumeration_digest(plan),
    }


# --- resource forecast --------------------------------------------------------


def forecast(plan: Plan) -> dict[str, Any]:
    """Deterministic file/forward/runtime/disk forecast for a plan."""
    test_files = len(plan.test_episodes()) * _episode_capture_files(
        plan.block_files, plan.max_blocks, max_level=2
    )
    calibration_files = len(plan.calibration_episode_list()) * _episode_capture_files(
        plan.block_files, plan.max_blocks, max_level=0
    )
    reference_files = plan.reference_files * len(plan.history_ids)
    bandwidth_files = plan.bandwidth_files * len(plan.history_ids)
    total_files = test_files + calibration_files + reference_files + bandwidth_files
    horizon_levels = len(plan.horizons)
    item_bytes = (85 + 3 * 128 + 3 * 128) * 4  # raw + 3 pooled + 3 pre-pooled (float32)
    waveform_bytes = 6 * ASSUMED_MEAN_STEPS * 4
    waveform_overhead = 1.15
    items_total = int(total_files * item_bytes)
    waveforms_total = int(total_files * waveform_bytes * waveform_overhead)
    meta_total = int(total_files * 900)
    total_bytes = items_total + waveforms_total + meta_total
    elapsed = total_files * len(ENCODER_SEEDS) / M18_MEASURED_FORWARDS_PER_S
    return {
        "window_size": {horizon: plan.window_size(horizon) for horizon in plan.horizons},
        "test_windows_per_horizon": len(plan.test_episodes()),
        "intervals_per_readout": len(plan.test_episodes()) * horizon_levels,
        "files": {
            "test": test_files,
            "calibration": calibration_files,
            "reference": reference_files,
            "bandwidth": bandwidth_files,
            "total": total_files,
        },
        "encoder_forwards": total_files * len(ENCODER_SEEDS),
        "model_loads": len(ENCODER_SEEDS),
        "generated_files": total_files,
        "cpu_permutations": 0,
        "cpu_permutations_note": "no permutation cell matrix; thresholds are pre-registered order statistics of 300 calibration windows",
        "measured_forward_rate_files_s": M18_MEASURED_FORWARDS_PER_S,
        "elapsed_s_estimate": int(elapsed),
        "elapsed_h_estimate": round(elapsed / 3600.0, 2),
        "bytes": {
            "items": items_total,
            "waveforms": waveforms_total,
            "meta_events": meta_total,
            "total": total_bytes,
            "declared_budget": DISK_BUDGET_BYTES,
        },
        "assumptions": (
            "forward rate is the measured M18 whole-matrix rate (generation+capture+scoring); "
            "waveform byte estimate assumes the plan mean step count and 15% npz overhead; "
            "disk must be re-checked at the explicit --out before capture"
        ),
    }


def _episode_capture_files(block_files: int, n_blocks: int, max_level: int) -> int:
    """Files needed per episode for a given highest materialized burden level."""
    counts = block_fault_counts(block_files)
    c5, c15, c27 = counts
    per_block = 0
    limit = (c5, c15, c27)[int(max_level)]
    for rank in range(block_files):
        abnormal = rank < limit
        twin = rank >= c5
        per_block += int(twin) + int(abnormal)
    return per_block * n_blocks



@dataclass(frozen=True)
class Episode:
    """One test or calibration episode with its frozen source block."""

    episode_id: str
    history_index: int
    cell_index: int
    episode_index: int
    base_index: int
    block_files: int
    n_blocks: int

    @property
    def history_id(self) -> str:
        return HISTORY_IDS[self.history_index]

    @property
    def history_seed(self) -> int:
        return HISTORY_SEEDS[self.history_index]

    @property
    def family(self) -> str:
        return FAMILIES[self.cell_index // len(SEVERITIES)]

    @property
    def severity(self) -> float:
        return SEVERITIES[self.cell_index % len(SEVERITIES)]

    @property
    def n_sources(self) -> int:
        return self.block_files * self.n_blocks

    def source_index(self, slot: int) -> int:
        if not 0 <= slot < self.n_sources:
            raise _refused("REFUSED-IDENTITY", "slot outside episode")
        return self.base_index + int(slot)

    def source_seed(self, slot: int) -> int:
        return int(derive_pair_seed(self.history_seed, self.source_index(slot)))

    def block_slots(self, block_index: int) -> range:
        if not 0 <= block_index < self.n_blocks:
            raise _refused("REFUSED-IDENTITY", "block outside episode")
        return range(block_index * self.block_files, (block_index + 1) * self.block_files)


@dataclass(frozen=True)
class Plan:
    """A complete frozen plan (official or smoke scale)."""

    label: str
    history_ids: tuple[str, ...]
    history_seeds: tuple[int, ...]
    cells: tuple[tuple[str, float], ...]
    horizons: Mapping[str, int]
    block_files: int
    episodes_per_cell: int
    calibration_episodes: int
    reference_files: int
    bandwidth_files: int
    calibration_quantile: float
    calibration_index_base: int
    test_index_base: int

    @property
    def cell_count(self) -> int:
        return len(self.cells)

    @property
    def max_blocks(self) -> int:
        return max(self.horizons.values())

    def window_size(self, horizon: str) -> int:
        return int(self.block_files) * int(self.horizons[str(horizon)])

    def fault_counts(self, horizon: str) -> tuple[int, ...]:
        counts = block_fault_counts(self.block_files)
        blocks = int(self.horizons[str(horizon)])
        return tuple(int(value) * blocks for value in counts)

    def test_episodes(self) -> list[Episode]:
        episodes: list[Episode] = []
        cursor = 0
        for cell_index in range(self.cell_count):
            for j in range(self.episodes_per_cell):
                history_index = j % len(self.history_ids)
                episodes.append(
                    Episode(
                        episode_id=f"S24PB-T-{history_index:02d}-{cell_index:02d}-{j:02d}",
                        history_index=history_index,
                        cell_index=cell_index,
                        episode_index=j // len(self.history_ids),
                        base_index=self.test_index_base + cursor * self._episode_sources,
                        block_files=self.block_files,
                        n_blocks=self.max_blocks,
                    )
                )
                cursor += 1
        self._assert_disjoint(episodes)
        return episodes

    def calibration_episode_list(self) -> list[Episode]:
        episodes: list[Episode] = []
        cursor = 0
        per_cell = self._calibration_per_cell()
        for cell_index, count in enumerate(per_cell):
            for j in range(count):
                history_index = j % len(self.history_ids)
                episodes.append(
                    Episode(
                        episode_id=f"S24PB-C-{history_index:02d}-{cell_index:02d}-{j:02d}",
                        history_index=history_index,
                        cell_index=cell_index,
                        episode_index=j // len(self.history_ids),
                        base_index=self.calibration_index_base + cursor * self._episode_sources,
                        block_files=self.block_files,
                        n_blocks=self.max_blocks,
                    )
                )
                cursor += 1
        self._assert_disjoint(episodes)
        return episodes

    @property
    def _episode_sources(self) -> int:
        return self.block_files * self.max_blocks

    def _calibration_per_cell(self) -> list[int]:
        base, extra = divmod(int(self.calibration_episodes), self.cell_count)
        return [base + (1 if index < extra else 0) for index in range(self.cell_count)]

    def _assert_disjoint(self, episodes: Sequence[Episode]) -> None:
        seen: set[int] = set()
        for episode in episodes:
            indices = {episode.source_index(slot) for slot in range(episode.n_sources)}
            if seen & indices:
                raise _refused("REFUSED-SEED-COLLISION", "episode source bands overlap")
            seen |= indices
        if seen & set(range(REFERENCE_INDEX_BASE, REFERENCE_INDEX_BASE + self.reference_files)):
            raise _refused("REFUSED-SEED-COLLISION", "episode overlaps reference band")
        bandwidth_base = REFERENCE_INDEX_BASE + self.reference_files
        if seen & set(range(bandwidth_base, bandwidth_base + self.bandwidth_files)):
            raise _refused("REFUSED-SEED-COLLISION", "episode overlaps bandwidth band")


def official_plan() -> Plan:
    counts = block_fault_counts(BLOCK_FILES)
    if counts != EXPECTED_FAULT_COUNTS["week"]:
        raise _refused("REFUSED-UNKNOWN-DESIGN", f"weekly counts drifted: {counts}")
    monthly = window_fault_counts("month", BLOCK_FILES)
    if monthly != EXPECTED_FAULT_COUNTS["month"]:
        raise _refused("REFUSED-UNKNOWN-DESIGN", f"monthly counts drifted: {monthly}")
    for start, end in RESERVED_SEED_BLOCKS:
        for seed in HISTORY_SEEDS:
            if start <= seed <= end:
                raise _refused("REFUSED-SEED-COLLISION", f"history seed {seed} in reserved block")
    if len(set(HISTORY_SEEDS)) != len(HISTORY_SEEDS):
        raise _refused("REFUSED-SEED-COLLISION", "history seeds are not unique")
    return Plan(
        label="official",
        history_ids=HISTORY_IDS,
        history_seeds=HISTORY_SEEDS,
        cells=tuple((family, severity) for family in FAMILIES for severity in SEVERITIES),
        horizons=dict(HORIZON_BLOCKS),
        block_files=BLOCK_FILES,
        episodes_per_cell=EPISODES_PER_CELL,
        calibration_episodes=CALIBRATION_EPISODE_COUNT,
        reference_files=REFERENCE_FILES,
        bandwidth_files=BANDWIDTH_FILES,
        calibration_quantile=CALIBRATION_QUANTILE,
        calibration_index_base=CALIBRATION_INDEX_BASE,
        test_index_base=TEST_INDEX_BASE,
    )



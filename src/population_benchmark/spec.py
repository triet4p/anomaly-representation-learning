def contract_payload(plan: Plan | None = None) -> dict[str, Any]:
    """Immutable contract body; its digest is the contract identity."""
    body = design_payload(plan)
    body["contract_version"] = 1
    body["supersedes"] = None
    body["historical_records"] = "accepted M17/M18/M19 contracts, caches and reports remain immutable"
    body["status"] = "FROZEN-PENDING-INDEPENDENT-REVIEW"
    return body


def contract_sha256(plan: Plan | None = None) -> str:
    return sha256_json(contract_payload(plan))


def verify_contract(payload: Mapping[str, Any], plan: Plan | None = None) -> dict[str, Any]:
    """Recompute the contract body and compare; refuse on any drift."""
    expected = contract_payload(plan)
    actual = {key: value for key, value in dict(payload).items() if key != "contract_sha256"}
    checks: list[dict[str, Any]] = []
    for key in sorted(set(expected) | set(actual)):
        checks.append({
            "check": f"field:{key}",
            "pass": expected.get(key) == actual.get(key),
        })
    recorded = payload.get("contract_sha256")
    checks.append({
        "check": "contract_sha256",
        "pass": recorded in (None, sha256_json(expected)),
        "recorded": recorded,
        "recomputed": sha256_json(expected),
    })
    failed = [item["check"] for item in checks if not item["pass"]]
    if failed:
        raise _refused("REFUSED-IDENTITY", f"contract drift: {failed[:5]}")
    return {"status": "CONTRACT-VERIFIED", "checks": len(checks), "sha256": sha256_json(expected)}


def validate_plan(plan: Plan) -> dict[str, Any]:
    """Structural validation of a plan before any capture."""
    checks: list[dict[str, Any]] = []
    checks.append({"check": "history_ids_unique", "pass": len(set(plan.history_ids)) == len(plan.history_ids)})
    checks.append({"check": "history_seeds_unique", "pass": len(set(plan.history_seeds)) == len(plan.history_seeds)})
    letters = {family for family in FAMILIES}
    full = plan.label == "official"
    checks.append({
        "check": "family_coverage",
        "pass": ({family for family, _ in plan.cells} == letters) if full else bool(plan.cells),
    })
    checks.append({
        "check": "severity_coverage",
        "pass": ({severity for _, severity in plan.cells} == set(SEVERITIES)) if full else bool(plan.cells),
    })
    counts = block_fault_counts(plan.block_files)
    checks.append({
        "check": "nested_counts",
        "pass": 0 < counts[0] < counts[1] < counts[2] <= plan.block_files,
    })
    test = plan.test_episodes()
    calibration = plan.calibration_episode_list()
    checks.append({
        "check": "episode_count",
        "pass": len(test) == plan.cell_count * plan.episodes_per_cell,
    })
    checks.append({
        "check": "calibration_count",
        "pass": len(calibration) == plan.calibration_episodes,
    })
    test_indices = {
        episode.source_index(slot) for episode in test for slot in range(episode.n_sources)
    }
    cal_indices = {
        episode.source_index(slot) for episode in calibration for slot in range(episode.n_sources)
    }
    ref = set(range(REFERENCE_INDEX_BASE, REFERENCE_INDEX_BASE + plan.reference_files))
    bw_base = REFERENCE_INDEX_BASE + plan.reference_files
    bw = set(range(bw_base, bw_base + plan.bandwidth_files))
    checks.append({"check": "test_calibration_disjoint", "pass": not (test_indices & cal_indices)})
    checks.append({"check": "roles_disjoint", "pass": not (test_indices & (ref | bw)) and not (cal_indices & (ref | bw)) and not (ref & bw)})
    failed = [item["check"] for item in checks if not item["pass"]]
    if failed:
        raise _refused("REFUSED-IDENTITY", f"plan validation failed: {failed}")
    return {"status": "PLAN-VALID", "checks": len(checks), "plan": summary(plan)}



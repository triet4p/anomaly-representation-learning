def block_fault_counts(block_files: int = BLOCK_FILES) -> tuple[int, int, int]:
    """Exact per-block fault counts for the 5%/15%/27.5% ladder.

    The ceiling rule is frozen before outcomes and reproduces the inherited
    M13/M15 table exactly at 40 files (2/6/11).
    """
    if block_files <= 0:
        raise _refused("REFUSED-UNKNOWN-DESIGN", "block size must be positive")
    counts = tuple(int(math.ceil(float(burden) * int(block_files))) for burden in BURDENS)
    if not (0 < counts[0] < counts[1] < counts[2] <= block_files):
        raise _refused("REFUSED-UNKNOWN-DESIGN", f"non-nesting block counts {counts}")
    return (counts[0], counts[1], counts[2])


def window_fault_counts(horizon: str, block_files: int = BLOCK_FILES) -> tuple[int, int, int]:
    """Per-window fault counts: block counts times the horizon block count."""
    blocks = HORIZON_BLOCKS[str(horizon)]
    counts = block_fault_counts(block_files)
    return tuple(int(value) * blocks for value in counts)  # type: ignore[return-value]


def window_size(horizon: str, block_files: int = BLOCK_FILES) -> int:
    return int(block_files) * HORIZON_BLOCKS[str(horizon)]


def rank_order(history_id: str, episode_id: str, block_index: int, n_block: int) -> list[int]:
    """Deterministic hash order of a block's GLOBAL slot indices.

    Labels never enter; ``block_index`` offsets the returned slots so callers
    can key membership and lineage by the episode-wide slot index.
    """
    if n_block <= 0:
        raise _refused("REFUSED-UNKNOWN-DESIGN", "block must be non-empty")
    base = int(block_index) * int(n_block)
    keyed = [
        (
            hashlib.sha256(
                f"{NULL_SEED}|{history_id}|{episode_id}|{int(block_index)}|{local}".encode("utf-8")
            ).hexdigest(),
            base + local,
        )
        for local in range(int(n_block))
    ]
    return [slot for _, slot in sorted(keyed)]


def block_membership(history_id: str, episode_id: str, block_index: int, n_block: int) -> dict[str, tuple[int, ...]]:
    """Nested per-block fault slots for the 5/15/27.5 compositions."""
    order = rank_order(history_id, episode_id, block_index, n_block)
    c5, c15, c27 = block_fault_counts(n_block)
    return {
        BURDEN_LABELS[0]: tuple(order[:c5]),
        BURDEN_LABELS[1]: tuple(order[:c15]),
        BURDEN_LABELS[2]: tuple(order[:c27]),
    }


def required_variants(rank: int, n_block: int, max_level: int) -> tuple[bool, bool]:
    """Which wave variants a source contributes (twin, abnormal).

    ``rank`` is the slot's position in the admitted hash order, ``max_level``
    is the highest burden index that must be materialized (2 for tests, 0 for
    calibration). A slot is normal in every composition above its fault rank,
    and abnormal in every composition at or below it.
    """
    counts = block_fault_counts(n_block)
    limit = (counts[0], counts[1], counts[2])[int(max_level)]
    return (bool(rank >= counts[0]), bool(rank < limit))


def coverage_reason(level: int) -> str:
    suffix = {0: "5", 1: "15", 2: "27_5"}[int(level)]
    return f"ABSTAIN-COVERAGE-{suffix}"


def episode_windows(
    *,
    episode: "Episode",
    plan: "Plan",
    admitted_ranks: Mapping[int, int | None],
    twin_ids: Mapping[int, str | None],
    abnormal_ids: Mapping[int, str | None],
    max_level: int,
) -> list[dict[str, Any]]:
    """Frozen nested window rosters shared by capture, replay and tests.

    Membership is the first ``ceil(burden * admitted_block_size)`` ranks of
    each block's frozen hash order. With all planned sources admitted this is
    exactly the inherited 2/6/11 (week-40) and 8/24/44 (month-160) table; with
    admission loss the fault count scales with the admitted block so the
    *requested burden fraction* is preserved (one-fault rounding). The monthly
    window is the union of the horizon's blocks, so 5% is nested in 15% nested
    in 27.5% over the SAME source roster.
    """
    counts = block_fault_counts(plan.block_files)
    admitted_by_block = {
        block: sorted(
            slot for slot in episode.block_slots(block) if admitted_ranks.get(slot) is not None
        )
        for block in range(episode.n_blocks)
    }
    windows: list[dict[str, Any]] = []
    for horizon, blocks in plan.horizons.items():
        if horizon == "week" and int(blocks) > 1:
            raise _refused("REFUSED-UNKNOWN-DESIGN", "weekly horizon must use exactly one block")
        for level_index in range(int(max_level) + 1):
            burden = BURDEN_LABELS[level_index]
            planned_count = int(counts[level_index])
            file_ids: list[str] = []
            files_missing = False
            blocks_short = False
            realized_faults = 0
            for block in range(int(blocks)):
                admitted = admitted_by_block.get(block, [])
                if len(admitted) < int(COVERAGE_FLOOR * plan.block_files):
                    blocks_short = True
                    continue
                faults = int(math.ceil(float(BURDENS[level_index]) * len(admitted)))
                realized_faults += faults
                for slot in admitted:
                    rank = int(admitted_ranks[slot])  # type: ignore[arg-type]
                    file_id = abnormal_ids.get(slot) if rank < faults else twin_ids.get(slot)
                    if file_id is None:
                        files_missing = True
                        continue
                    file_ids.append(str(file_id))
            planned_size = plan.window_size(horizon)
            realized = len(file_ids)
            if blocks_short or files_missing or realized < int(COVERAGE_FLOOR * planned_size):
                coverage = coverage_reason(level_index)
            else:
                coverage = "COVERED"
            windows.append({
                "window_id": f"{episode.episode_id}:{horizon}:{burden}",
                "horizon": str(horizon),
                "burden": str(burden),
                "cell_index": int(episode.cell_index),
                "family": str(episode.family),
                "severity": float(episode.severity),
                "file_ids": list(file_ids),
                "requested_faults": int(planned_count * int(blocks)),
                "realized_faults": int(realized_faults),
                "n_files": int(realized),
                "planned_files": int(planned_size),
                "realized_burden": (float(realized_faults) / realized) if realized else None,
                "requested_burden": float(BURDENS[level_index]),
                "calendar": {
                    "unit": str(horizon),
                    "episode_id": episode.episode_id,
                    "history_seed": int(episode.history_seed),
                    "block_indices": list(range(int(blocks))),
                    "time_basis": "deterministic synthetic block index, not a wall-clock time base",
                },
                "coverage": coverage,
            })
    return windows


